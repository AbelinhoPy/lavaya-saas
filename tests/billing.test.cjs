const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const ts=require('typescript');
const fs=require('node:fs');
function load(file){const source=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;const m={exports:{}};new Function('require','module','exports',source)(require,m,m.exports);return m.exports;}
const {verifySignature,hasAccess,validPrice}=load('src/lib/billing-core.ts');
const {validJob,canAdvance}=load('src/lib/jobs.ts');
const now=Date.now(),timestamp=String(Math.floor(now/1000)),body='{"event_id":"evt_test"}',secret='test-only-secret';
const signature=crypto.createHmac('sha256',secret).update(`${timestamp}:${body}`).digest('hex');
assert.equal(verifySignature(body,`ts=${timestamp};h1=${signature}`,secret,now),true);
assert.equal(verifySignature(body+' ',`ts=${timestamp};h1=${signature}`,secret,now),false);
assert.equal(verifySignature(body,`ts=${timestamp};h1=${signature}`,secret,now+6000),false);
assert.equal(verifySignature(body,`ts=${timestamp};h1=bad`,secret,now),false);
assert.equal(verifySignature(body,`ts=${timestamp};h1=${signature}`,'wrong',now),false);
assert.equal(hasAccess(null,now),false);
assert.equal(hasAccess({status:'trialing',access_until:new Date(now+10000).toISOString()},now),true);
for(const status of ['active','trialing','past_due','paused','canceled'])assert.equal(hasAccess({status,access_until:new Date(now-1000).toISOString()},now),false);
assert.equal(hasAccess({status:'past_due',access_until:new Date(now+10000).toISOString()},now),false);
const price={status:'active',billing_cycle:{interval:'month',frequency:1},trial_period:{interval:'day',frequency:7,requires_payment_method:true},unit_price:{amount:'2000',currency_code:'USD'}};
assert.equal(validPrice(price,'2000'),true);
assert.equal(validPrice({...price,trial_period:{...price.trial_period,requires_payment_method:false}},'2000'),false);
assert.equal(validPrice({...price,trial_period:{...price.trial_period,unit_price:{amount:'1'}}},'2000'),false);
assert.equal(validPrice(price,'2900'),false);
assert.equal(validPrice({...price,unit_price_overrides:[{}]},'2000'),false);
assert.equal(validJob({plate:'ABC 123',service:'Lavado',amount:50000}),true);
assert.equal(validJob({plate:'<script>',service:'Lavado',amount:50000}),false);
assert.equal(validJob({plate:'ABC 123',service:'Lavado',amount:-1}),false);
assert.equal(validJob({plate:'ABC 123',service:'Lavado',amount:1.5}),false);
assert.equal(canAdvance('espera','lavando'),true);
assert.equal(canAdvance('espera','entregado'),false);
assert.equal(canAdvance('entregado',undefined),false);
console.log('PASS: webhook signatures, tampering/replay, subscription expiry, price/trial, input validation and transitions');
